class DistanceUnit
{
    //required  classes
    public static double KmToMiles(double km)
    {
        km * 0.621371;
    }
    public static double MilesToKm(double miles)
    {
        miles * 1.60934;
    }
    public static double MetersToFeet(double meters)
    {
        meters * 3.28084;
    }
    public static double FeetToMeters(double feet)
    {
        feet * 0.3048;
    }
}
